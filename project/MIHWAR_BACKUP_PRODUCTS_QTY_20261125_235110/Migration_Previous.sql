  UPDATE public.inventory_count_sessions
     SET status = 'rejected', rejected_by = auth.uid(), rejected_at = now(),
         rejection_reason = trim(p_reason), updated_at = now()
   WHERE id = p_session_id;
  INSERT INTO public.inventory_count_events(session_id, organization_id, branch_id, action, from_status, to_status, notes, actor_id)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'rejected', 'in_review', 'rejected', trim(p_reason), auth.uid());
  RETURN jsonb_build_object('ok', true, 'status', 'rejected');
END;
$$;

CREATE OR REPLACE FUNCTION public.approve_inventory_count(p_session_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session public.inventory_count_sessions%ROWTYPE;
  v_item public.inventory_count_items%ROWTYPE;
  v_surplus_qty numeric(18,3) := 0;
  v_shortage_qty numeric(18,3) := 0;
  v_surplus_value numeric(18,2) := 0;
  v_shortage_value numeric(18,2) := 0;
  v_net numeric(18,2) := 0;
  v_current_qty numeric(18,3);
BEGIN
  SELECT * INTO v_session FROM public.inventory_count_sessions WHERE id = p_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'جلسة الجرد غير موجودة'; END IF;
  IF NOT public.can_manage_inventory_count(v_session.organization_id, v_session.branch_id) THEN
    RAISE EXCEPTION 'غير مصرح باعتماد جلسة الجرد';
  END IF;
  IF v_session.status <> 'in_review' THEN RAISE EXCEPTION 'يمكن اعتماد الجلسات قيد المراجعة فقط'; END IF;
  IF EXISTS (SELECT 1 FROM public.inventory_count_items WHERE session_id = p_session_id AND physical_quantity IS NULL) THEN
    RAISE EXCEPTION 'توجد أصناف لم يتم جردها';
  END IF;

  -- Lock and verify every snapshot row (including zero-difference items).
  FOR v_item IN
    SELECT * FROM public.inventory_count_items
    WHERE session_id = p_session_id
    ORDER BY product_id
    FOR UPDATE
  LOOP
    SELECT p.quantity INTO v_current_qty
      FROM public.products p
     WHERE p.id = v_item.product_id
       AND p.organization_id = v_session.organization_id
       AND p.shop_id = v_session.branch_id
     FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'الصنف % لم يعد تابعًا للفرع المحدد', v_item.product_code;
    END IF;
    IF COALESCE(v_current_qty, 0) <> v_item.system_quantity THEN
      RAISE EXCEPTION 'تغير رصيد الصنف % بعد بدء الجرد؛ حدّث الجلسة وأعد المراجعة', v_item.product_code;
    END IF;
    IF v_item.physical_quantity <> trunc(v_item.physical_quantity) THEN
      RAISE EXCEPTION 'الكمية الفعلية للصنف % يجب أن تكون عددًا صحيحًا لأن products.quantity من نوع integer', v_item.product_code;
    END IF;
    IF v_item.difference <> 0 AND COALESCE(v_item.unit_cost, 0) <= 0 THEN
      RAISE EXCEPTION 'لا توجد تكلفة شراء موثوقة للصنف %؛ لا يمكن اعتماد فرق مالي دون تكلفة', v_item.product_code;
    END IF;

    IF v_item.difference = 0 THEN
      CONTINUE;
    END IF;

    UPDATE public.products
       SET quantity = v_item.physical_quantity::integer,
           updated_at = now()
     WHERE id = v_item.product_id
       AND organization_id = v_session.organization_id
       AND shop_id = v_session.branch_id;

    INSERT INTO public.gl_stock_moves (
      organization_id, branch_id, product_id, move_type, qty,
      unit_cost, ref_type, ref_id, notes, created_by
    ) VALUES (
      v_session.organization_id, v_session.branch_id,
      v_item.product_id, 'adjust', v_item.difference,
      v_item.unit_cost, 'inventory_count', p_session_id,
      COALESCE(NULLIF(v_item.notes, ''), 'اعتماد جرد ' || v_session.reference_no), auth.uid()
    );
  END LOOP;

  SELECT
    COALESCE(sum(difference) FILTER (WHERE difference > 0), 0),
    COALESCE(sum(abs(difference)) FILTER (WHERE difference < 0), 0),
    COALESCE(sum(difference_value) FILTER (WHERE difference_value > 0), 0),
    COALESCE(sum(abs(difference_value)) FILTER (WHERE difference_value < 0), 0)
  INTO v_surplus_qty, v_shortage_qty, v_surplus_value, v_shortage_value
  FROM public.inventory_count_items WHERE session_id = p_session_id;
  v_net := v_surplus_value - v_shortage_value;

  UPDATE public.inventory_count_sessions
     SET status = 'approved', approved_by = auth.uid(), approved_at = now(),
         posted_at = now(), updated_at = now(),
         accounting_status = CASE WHEN v_surplus_value = 0 AND v_shortage_value = 0 THEN 'not_required' ELSE 'not_posted' END
   WHERE id = p_session_id;

  INSERT INTO public.inventory_count_events(session_id, organization_id, branch_id, action, from_status, to_status, notes, actor_id)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'approved', 'in_review', 'approved', 'تم اعتماد فروق الجرد وترحيل حركات المخزون', auth.uid());

  RETURN jsonb_build_object(
    'ok', true, 'status', 'approved', 'surplus_quantity', v_surplus_qty,
    'shortage_quantity', v_shortage_qty, 'surplus_value', v_surplus_value,
    'shortage_value', v_shortage_value, 'net_difference', v_net
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.post_inventory_count_journal(
  p_session_id bigint,
  p_inventory_account_id bigint,
  p_surplus_account_id bigint,
  p_shortage_account_id bigint,
  p_description text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session public.inventory_count_sessions%ROWTYPE;
  v_surplus_value numeric(18,2) := 0;
  v_shortage_value numeric(18,2) := 0;
  v_entry_year integer;
  v_entry_no integer;
  v_entry_id bigint;
  v_account_count integer;
BEGIN
  SELECT * INTO v_session
  FROM public.inventory_count_sessions
  WHERE id = p_session_id
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'جلسة الجرد غير موجودة'; END IF;
  IF NOT public.can_manage_inventory_count(v_session.organization_id, v_session.branch_id) THEN
    RAISE EXCEPTION 'غير مصرح بإنشاء القيد المحاسبي';
  END IF;
  IF v_session.status <> 'approved' THEN RAISE EXCEPTION 'يجب اعتماد الجرد قبل إنشاء القيد'; END IF;
  IF v_session.accounting_entry_id IS NOT NULL THEN
    RETURN jsonb_build_object('ok', true, 'already_posted', true, 'entry_id', v_session.accounting_entry_id);
  END IF;

  SELECT
    COALESCE(sum(difference_value) FILTER (WHERE difference_value > 0), 0),
    COALESCE(sum(abs(difference_value)) FILTER (WHERE difference_value < 0), 0)
  INTO v_surplus_value, v_shortage_value
  FROM public.inventory_count_items
  WHERE session_id = p_session_id;

  IF v_surplus_value = 0 AND v_shortage_value = 0 THEN
    UPDATE public.inventory_count_sessions
       SET accounting_status = 'not_required', updated_at = now()
     WHERE id = p_session_id;
    RETURN jsonb_build_object('ok', true, 'not_required', true);
  END IF;

  IF p_inventory_account_id IS NULL
     OR (v_surplus_value > 0 AND p_surplus_account_id IS NULL)
     OR (v_shortage_value > 0 AND p_shortage_account_id IS NULL) THEN
    RAISE EXCEPTION 'يجب تحديد حسابات المخزون والفائض والعجز المطلوبة';
  END IF;
  IF p_inventory_account_id = p_surplus_account_id
     OR p_inventory_account_id = p_shortage_account_id
     OR (v_surplus_value > 0 AND v_shortage_value > 0 AND p_surplus_account_id = p_shortage_account_id) THEN
    RAISE EXCEPTION 'يجب اختيار حسابات مختلفة للمخزون والفائض والعجز';
  END IF;

  SELECT count(*) INTO v_account_count
  FROM public.gl_accounts a
  WHERE a.organization_id = v_session.organization_id
    AND a.is_group = false
    AND a.id IN (
      p_inventory_account_id,
      CASE WHEN v_surplus_value > 0 THEN p_surplus_account_id ELSE NULL END,
      CASE WHEN v_shortage_value > 0 THEN p_shortage_account_id ELSE NULL END
    );
  IF v_account_count <> (1 + CASE WHEN v_surplus_value > 0 THEN 1 ELSE 0 END + CASE WHEN v_shortage_value > 0 THEN 1 ELSE 0 END) THEN
    RAISE EXCEPTION 'أحد الحسابات المحددة غير موجود أو لا يتبع المؤسسة';
  END IF;

  v_entry_year := EXTRACT(YEAR FROM v_session.count_date)::integer;
  PERFORM pg_advisory_xact_lock(hashtextextended(v_session.organization_id::text || ':' || v_entry_year::text, 0));
  LOCK TABLE public.gl_journal_entries IN SHARE ROW EXCLUSIVE MODE;
  SELECT COALESCE(MAX(e.entry_no), 0) + 1
    INTO v_entry_no
  FROM public.gl_journal_entries e
  WHERE e.organization_id = v_session.organization_id
    AND e.entry_year = v_entry_year;

  INSERT INTO public.gl_journal_entries (
    organization_id, entry_no, entry_year, date, description,
    branch_id, entry_type, notes, status
  ) VALUES (
    v_session.organization_id, v_entry_no, v_entry_year, v_session.count_date,
    COALESCE(NULLIF(trim(p_description), ''), 'تسوية فروق جرد المخزون ' || v_session.reference_no),
    v_session.branch_id, 'adjustment', v_session.description, 'posted'
  ) RETURNING id INTO v_entry_id;

  IF v_surplus_value > 0 THEN
    INSERT INTO public.gl_journal_lines (entry_id, account_id, debit, credit, branch_id, note, party_id)
    VALUES
      (v_entry_id, p_inventory_account_id, v_surplus_value, 0, v_session.branch_id, COALESCE(NULLIF(trim(p_description), ''), 'Inventory count adjustment') || ' · ' || v_session.reference_no, NULL),
      (v_entry_id, p_surplus_account_id, 0, v_surplus_value, v_session.branch_id, COALESCE(NULLIF(trim(p_description), ''), 'Inventory count adjustment') || ' · ' || v_session.reference_no, NULL);
  END IF;

  IF v_shortage_value > 0 THEN
    INSERT INTO public.gl_journal_lines (entry_id, account_id, debit, credit, branch_id, note, party_id)
    VALUES
      (v_entry_id, p_shortage_account_id, v_shortage_value, 0, v_session.branch_id, COALESCE(NULLIF(trim(p_description), ''), 'Inventory count adjustment') || ' · ' || v_session.reference_no, NULL),
      (v_entry_id, p_inventory_account_id, 0, v_shortage_value, v_session.branch_id, COALESCE(NULLIF(trim(p_description), ''), 'Inventory count adjustment') || ' · ' || v_session.reference_no, NULL);
  END IF;

  UPDATE public.inventory_count_sessions
     SET accounting_entry_id = v_entry_id, accounting_status = 'posted', updated_at = now()
   WHERE id = p_session_id;

  INSERT INTO public.inventory_count_journal_links(session_id, organization_id, branch_id, state, entry_id, updated_at)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'posted', v_entry_id, now())
  ON CONFLICT (session_id) DO UPDATE
    SET state = 'posted', entry_id = EXCLUDED.entry_id, updated_at = now();

  INSERT INTO public.inventory_count_events(session_id, organization_id, branch_id, action, from_status, to_status, notes, actor_id)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'journal_posted', 'approved', 'approved', 'تم إنشاء القيد المحاسبي رقم ' || v_entry_no || '/' || v_entry_year, auth.uid());

  RETURN jsonb_build_object('ok', true, 'entry_id', v_entry_id, 'entry_no', v_entry_no, 'entry_year', v_entry_year);
END;
$$;

