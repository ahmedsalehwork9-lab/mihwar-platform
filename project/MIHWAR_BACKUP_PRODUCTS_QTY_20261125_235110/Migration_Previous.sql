-- MIHWAR CLOUD ERP: Inventory count sessions, review, approval and audit trail.
-- REVIEW ONLY: this migration is delivered for manual review and is NOT applied automatically.
-- Prerequisites already used by this project:
-- shops, products, warehouses, gl_stock_moves, profiles.
-- Assumes products.quantity is integer and products.shop_id identifies the branch.
-- Cost snapshot is weighted net purchase cost (purchase_in + purchase_return) from gl_stock_moves; no products.price fallback.

CREATE SEQUENCE IF NOT EXISTS public.inventory_count_reference_seq;

-- This migration intentionally uses products.quantity as the sole book balance.
-- warehouses is retained only as the selected count-session scope/label.

CREATE TABLE IF NOT EXISTS public.inventory_count_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL,
  branch_id bigint NOT NULL REFERENCES public.shops(id) ON DELETE RESTRICT,
  warehouse_id bigint NOT NULL REFERENCES public.warehouses(id) ON DELETE RESTRICT,
  reference_no text NOT NULL,
  count_date date NOT NULL DEFAULT CURRENT_DATE,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'in_review', 'approved', 'rejected')),
  description text,
  notes text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  submitted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  approved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  approved_at timestamptz,
  rejected_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  rejected_at timestamptz,
  rejection_reason text,
  posted_at timestamptz,
  accounting_entry_id bigint,
  accounting_status text NOT NULL DEFAULT 'not_posted'
    CHECK (accounting_status IN ('not_posted', 'posted', 'not_required')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_count_session_reference_unique UNIQUE (organization_id, reference_no)
);

CREATE TABLE IF NOT EXISTS public.inventory_count_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES public.inventory_count_sessions(id) ON DELETE CASCADE,
  organization_id bigint NOT NULL,
  branch_id bigint NOT NULL,
  warehouse_id bigint NOT NULL,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  product_code text,
  product_name text NOT NULL,
  category text,
  unit_name text NOT NULL DEFAULT 'قطعة',
  system_quantity numeric(18,3) NOT NULL DEFAULT 0,
  physical_quantity numeric(18,3),
  difference numeric(18,3) NOT NULL DEFAULT 0,
  unit_cost numeric(18,4) NOT NULL DEFAULT 0,
  difference_value numeric(18,2) NOT NULL DEFAULT 0,
  notes text,
  counted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  counted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_count_item_unique_product UNIQUE (session_id, product_id),
  CONSTRAINT inventory_count_system_qty_nonnegative CHECK (system_quantity >= 0),
  CONSTRAINT inventory_count_physical_qty_nonnegative CHECK (physical_quantity IS NULL OR physical_quantity >= 0),
  CONSTRAINT inventory_count_unit_cost_nonnegative CHECK (unit_cost >= 0)
);

CREATE TABLE IF NOT EXISTS public.inventory_count_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES public.inventory_count_sessions(id) ON DELETE CASCADE,
  organization_id bigint NOT NULL,
  branch_id bigint NOT NULL,
  action text NOT NULL,
  from_status text,
  to_status text,
  notes text,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- A reservation row prevents the UI from creating duplicate journal entries when a user retries.
CREATE TABLE IF NOT EXISTS public.inventory_count_journal_links (
  session_id bigint PRIMARY KEY REFERENCES public.inventory_count_sessions(id) ON DELETE CASCADE,
  organization_id bigint NOT NULL,
  branch_id bigint NOT NULL,
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'posted')),
  entry_id bigint UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_inventory_count_sessions_scope_date
  ON public.inventory_count_sessions (organization_id, branch_id, warehouse_id, count_date DESC);
CREATE INDEX IF NOT EXISTS idx_inventory_count_sessions_status
  ON public.inventory_count_sessions (organization_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_inventory_count_items_session
  ON public.inventory_count_items (session_id, product_name);
CREATE INDEX IF NOT EXISTS idx_inventory_count_events_session
  ON public.inventory_count_events (session_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_gl_stock_moves_inventory_count_product
  ON public.gl_stock_moves (ref_type, ref_id, product_id)
  WHERE ref_type = 'inventory_count' AND ref_id IS NOT NULL;

-- Supports the branch access model already used by AuthContext (admin, store_id,
-- shop owner, and my_branches() when that RPC exists for group managers).
CREATE OR REPLACE FUNCTION public.can_manage_inventory_count(p_org_id bigint, p_branch_id bigint)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_admin boolean := false;
  v_store_id bigint;
  v_allowed boolean := false;
BEGIN
  IF auth.uid() IS NULL THEN RETURN false; END IF;

  SELECT (COALESCE(p.is_admin, false) OR p.role::text = 'admin'), p.store_id
    INTO v_admin, v_store_id
  FROM public.profiles p
  WHERE p.id = auth.uid();

  IF COALESCE(v_admin, false) THEN RETURN true; END IF;
  IF v_store_id = p_branch_id THEN RETURN true; END IF;

  IF EXISTS (
    SELECT 1 FROM public.shops s
    WHERE s.id = p_branch_id
      AND s.organization_id = p_org_id
      AND s.owner_id = auth.uid()
  ) THEN RETURN true; END IF;

  IF to_regprocedure('public.my_branches()') IS NOT NULL THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM public.my_branches() b WHERE b.id = $1)'
      INTO v_allowed USING p_branch_id;
    IF v_allowed AND EXISTS (
      SELECT 1 FROM public.shops s
      WHERE s.id = p_branch_id AND s.organization_id = p_org_id
    ) THEN RETURN true; END IF;
  END IF;

  RETURN false;
END;
$$;

