CREATE OR REPLACE FUNCTION public.create_inventory_count_session(
  p_org_id bigint,
  p_branch_id bigint,
  p_warehouse_id bigint,
  p_count_date date DEFAULT CURRENT_DATE,
  p_description text DEFAULT NULL,
  p_product_ids bigint[] DEFAULT NULL,
  p_category text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session_id bigint;
  v_reference text;
  v_count integer;
BEGIN
  IF NOT public.can_manage_inventory_count(p_org_id, p_branch_id) THEN
    RAISE EXCEPTION 'غير مصرح بإنشاء جلسة جرد لهذا الفرع';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.warehouses w
    WHERE w.id = p_warehouse_id
      AND w.organization_id = p_org_id
      AND w.branch_id IS NOT DISTINCT FROM p_branch_id
  ) THEN
    RAISE EXCEPTION 'المستودع لا يتبع المؤسسة والفرع المحددين';
  END IF;

  v_reference := 'IC-' || to_char(COALESCE(p_count_date, CURRENT_DATE), 'YYYY') || '-' ||
    lpad(nextval('public.inventory_count_reference_seq')::text, 6, '0');

  INSERT INTO public.inventory_count_sessions (
    organization_id, branch_id, warehouse_id, reference_no, count_date,
    description, created_by, status
  ) VALUES (
    p_org_id, p_branch_id, p_warehouse_id, v_reference, COALESCE(p_count_date, CURRENT_DATE),
    NULLIF(trim(p_description), ''), auth.uid(), 'draft'
  ) RETURNING id INTO v_session_id;

  INSERT INTO public.inventory_count_items (
    session_id, organization_id, branch_id, warehouse_id, product_id,
    product_code, product_name, category, unit_name,
    system_quantity, unit_cost, difference, difference_value
  )
  SELECT
    v_session_id, p_org_id, p_branch_id, p_warehouse_id, p.id,
    p.product_code, COALESCE(NULLIF(p.product_name, ''), '—'), p.category,
    COALESCE(NULLIF(to_jsonb(p)->>'unit', ''), NULLIF(to_jsonb(p)->>'unit_name', ''), 'قطعة'),
    COALESCE(p.quantity, 0), COALESCE(cost.avg_unit_cost, 0), 0, 0
  FROM public.products p
  LEFT JOIN LATERAL (
    SELECT CASE WHEN sum(m.qty) FILTER (WHERE m.move_type IN ('purchase_in', 'purchase_return')) > 0
      THEN sum(m.qty * m.unit_cost) FILTER (WHERE m.move_type IN ('purchase_in', 'purchase_return')) / sum(m.qty) FILTER (WHERE m.move_type IN ('purchase_in', 'purchase_return'))
      ELSE 0 END AS avg_unit_cost
    FROM public.gl_stock_moves m
    WHERE m.organization_id = p_org_id
      AND m.branch_id = p_branch_id
      AND m.product_id = p.id
      AND m.move_type IN ('purchase_in', 'purchase_return')
      AND m.qty <> 0
      AND m.unit_cost > 0
  ) cost ON true
  WHERE p.organization_id = p_org_id
    AND p.shop_id = p_branch_id
    AND (p_product_ids IS NULL OR p.id = ANY(p_product_ids))
    AND (NULLIF(trim(p_category), '') IS NULL OR COALESCE(p.category, '') = p_category)
  ORDER BY p.product_name, p.id;

  GET DIAGNOSTICS v_count = ROW_COUNT;
  IF v_count = 0 THEN
    RAISE EXCEPTION 'لا توجد أصناف مطابقة لإنشاء جلسة الجرد';
  END IF;

  INSERT INTO public.inventory_count_events (
    session_id, organization_id, branch_id, action, to_status, notes, actor_id
  ) VALUES (
    v_session_id, p_org_id, p_branch_id, 'created', 'draft', 'تم إنشاء جلسة الجرد والتقاط الرصيد من products.quantity', auth.uid()
  );

  RETURN jsonb_build_object('ok', true, 'id', v_session_id, 'reference_no', v_reference, 'items_count', v_count);
END;
$$;

CREATE OR REPLACE FUNCTION public.save_inventory_count_items(
  p_session_id bigint,
  p_items jsonb
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session public.inventory_count_sessions%ROWTYPE;
  v_item record;
  v_updated integer := 0;
  v_rows integer := 0;
BEGIN
  SELECT * INTO v_session FROM public.inventory_count_sessions
  WHERE id = p_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'جلسة الجرد غير موجودة'; END IF;
  IF NOT public.can_manage_inventory_count(v_session.organization_id, v_session.branch_id) THEN
    RAISE EXCEPTION 'غير مصرح بتعديل جلسة الجرد';
  END IF;
  IF v_session.status <> 'draft' THEN RAISE EXCEPTION 'لا يمكن تعديل جلسة ليست مسودة'; END IF;
  IF jsonb_typeof(p_items) <> 'array' THEN RAISE EXCEPTION 'صيغة تفاصيل الجرد غير صحيحة'; END IF;

  FOR v_item IN
    SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id bigint, physical_quantity numeric, notes text)
  LOOP
    IF v_item.product_id IS NULL OR (v_item.physical_quantity IS NOT NULL AND (v_item.physical_quantity < 0 OR v_item.physical_quantity <> trunc(v_item.physical_quantity))) THEN
      RAISE EXCEPTION 'الكمية الفعلية يجب أن تكون عددًا صحيحًا صفرًا أو أكبر لأن رصيد بطاقة الصنف integer';
    END IF;

    UPDATE public.inventory_count_items i
       SET physical_quantity = CASE WHEN v_item.physical_quantity IS NULL THEN i.physical_quantity ELSE round(v_item.physical_quantity, 3) END,
           difference = CASE WHEN v_item.physical_quantity IS NULL THEN i.difference ELSE round(v_item.physical_quantity - i.system_quantity, 3) END,
           difference_value = CASE WHEN v_item.physical_quantity IS NULL THEN i.difference_value ELSE round((v_item.physical_quantity - i.system_quantity) * i.unit_cost, 2) END,
           notes = NULLIF(trim(v_item.notes), ''),
           counted_by = auth.uid(), counted_at = now(), updated_at = now()
     WHERE i.session_id = p_session_id AND i.product_id = v_item.product_id;

    GET DIAGNOSTICS v_rows = ROW_COUNT;
    v_updated := v_updated + v_rows;
  END LOOP;

  UPDATE public.inventory_count_sessions SET updated_at = now() WHERE id = p_session_id;
  INSERT INTO public.inventory_count_events(session_id, organization_id, branch_id, action, from_status, to_status, notes, actor_id)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'draft_saved', 'draft', 'draft', 'تم حفظ كميات الجرد', auth.uid());

  RETURN jsonb_build_object('ok', true, 'updated_items', v_updated);
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_inventory_count_for_review(p_session_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session public.inventory_count_sessions%ROWTYPE;
  v_total integer;
  v_counted integer;
BEGIN
  SELECT * INTO v_session FROM public.inventory_count_sessions WHERE id = p_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'جلسة الجرد غير موجودة'; END IF;
  IF NOT public.can_manage_inventory_count(v_session.organization_id, v_session.branch_id) THEN
    RAISE EXCEPTION 'غير مصرح بإرسال الجرد للمراجعة';
  END IF;
  IF v_session.status <> 'draft' THEN RAISE EXCEPTION 'الجلسة ليست في حالة مسودة'; END IF;
  SELECT count(*), count(*) FILTER (WHERE physical_quantity IS NOT NULL)
    INTO v_total, v_counted FROM public.inventory_count_items WHERE session_id = p_session_id;
  IF v_total = 0 OR v_total <> v_counted THEN
    RAISE EXCEPTION 'يجب إدخال الكمية الفعلية لجميع الأصناف قبل الإرسال للمراجعة';
  END IF;
  UPDATE public.inventory_count_sessions
     SET status = 'in_review', submitted_by = auth.uid(), updated_at = now()
   WHERE id = p_session_id;
  INSERT INTO public.inventory_count_events(session_id, organization_id, branch_id, action, from_status, to_status, actor_id)
  VALUES (p_session_id, v_session.organization_id, v_session.branch_id, 'submitted', 'draft', 'in_review', auth.uid());
  RETURN jsonb_build_object('ok', true, 'status', 'in_review');
END;
$$;

CREATE OR REPLACE FUNCTION public.reject_inventory_count(p_session_id bigint, p_reason text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session public.inventory_count_sessions%ROWTYPE;
BEGIN
  SELECT * INTO v_session FROM public.inventory_count_sessions WHERE id = p_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'جلسة الجرد غير موجودة'; END IF;
  IF NOT public.can_manage_inventory_count(v_session.organization_id, v_session.branch_id) THEN
    RAISE EXCEPTION 'غير مصرح برفض جلسة الجرد';
  END IF;
  IF v_session.status <> 'in_review' THEN RAISE EXCEPTION 'يمكن رفض الجلسات قيد المراجعة فقط'; END IF;
